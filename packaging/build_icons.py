"""Build frontend/css/icons.css from packaging/icons.json.

Each icon becomes a class `.ic-<name>` drawn with a CSS mask, so it takes the text colour and
scales with font size. SVGs are kept in frontend/vendor/icons/<pack>/; a missing one is fetched
once from the pinned package version (dev machines only; the app never fetches icons).

`_variants` in icons.json swaps icons under a selector (the Design menu's choices): each variant
has `selector` with `{name}` for the icon name and `icons` {name: "<pack>/<file>"}.

The colour file icons are images, not masks. `_material`: the Material Icon Theme's own map of
extensions, file names and folder names to icons, written to js/fileicons-material.js, with every
icon it names kept in vendor/icons/material/ (the browser loads only those on screen). `_fluent`:
one Fluent Emoji file per file kind in vendor/icons/fluent-emoji/ (Design menu).

    python packaging/build_icons.py
"""
from __future__ import annotations

import hashlib
import json
import sys
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "packaging" / "icons.json"
VENDOR = ROOT / "frontend" / "vendor" / "icons"
OUT = ROOT / "frontend" / "css" / "icons.css"
MATERIAL_JS = ROOT / "frontend" / "js" / "fileicons-material.js"

# Pinned sources. Phosphor (MIT), Tabler (MIT), Lucide (ISC), Material Icon Theme (MIT).
_PH = "https://cdn.jsdelivr.net/npm/@phosphor-icons/core@2.1.1/"
PACKS = {
    "phosphor": (_PH + "assets/regular/{}.svg", _PH + "LICENSE"),
    **{f"phosphor-{w}": (_PH + f"assets/{w}/{{}}.svg", _PH + "LICENSE") for w in ("light", "thin", "fill", "duotone")},
    "tabler": ("https://cdn.jsdelivr.net/npm/@tabler/icons@3.48.0/icons/outline/{}.svg",
               "https://cdn.jsdelivr.net/npm/@tabler/icons@3.48.0/LICENSE"),
    "tabler-filled": ("https://cdn.jsdelivr.net/npm/@tabler/icons@3.48.0/icons/filled/{}.svg",
                      "https://cdn.jsdelivr.net/npm/@tabler/icons@3.48.0/LICENSE"),
    "material": ("https://cdn.jsdelivr.net/npm/material-icon-theme@5.27.0/icons/{}.svg",
                 "https://cdn.jsdelivr.net/npm/material-icon-theme@5.27.0/LICENSE"),
    "lucide": ("https://cdn.jsdelivr.net/npm/lucide-static@1.48.0/icons/{}.svg",
               "https://cdn.jsdelivr.net/npm/lucide-static@1.48.0/LICENSE"),
}

HEADER = """/* Generated by packaging/build_icons.py from packaging/icons.json - do not edit by hand. */
.ic { display: inline-block; width: 1.15em; height: 1.15em; flex-shrink: 0; vertical-align: -0.2em;
      background-color: currentColor; -webkit-mask: var(--ic) center / contain no-repeat; mask: var(--ic) center / contain no-repeat; }
"""


def _fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read()


def _svg(pack: str, name: str) -> str:
    path = VENDOR / pack / f"{name}.svg"
    if not path.exists():
        if pack not in PACKS:
            sys.exit(f"missing {path} and {pack!r} has no download source")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(_fetch(PACKS[pack][0].format(name)))
        lic = path.parent / "LICENSE.txt"
        if not lic.exists():
            lic.write_bytes(_fetch(PACKS[pack][1]))
        print(f"fetched {pack}/{name}")
    return path.read_text(encoding="utf-8")


def _uri(svg: str) -> str:
    svg = " ".join(svg.split())
    if "xmlns=" not in svg:
        svg = svg.replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"', 1)
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe=" /=:;,'-.")


def _rule(selector: str, src: str) -> str:
    pack, _, file = src.partition("/")
    return f'{selector} {{ --ic: url("{_uri(_svg(pack, file))}"); }}\n'


def _fetch_files(jobs: list[tuple[str, Path]]) -> None:
    """Download each (url, path) that is missing, a few at a time."""
    todo = [(u, p) for u, p in jobs if not p.exists()]
    if not todo:
        return

    def one(job):
        url, path = job
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(_fetch(url))

    with ThreadPoolExecutor(16) as pool:
        list(pool.map(one, todo))
    print(f"fetched {len(todo)} file(s)")


def build_material(cfg: dict) -> None:
    """js/fileicons-material.js from the theme's manifest, plus every icon it names."""
    version = cfg["version"]
    stamp = hashlib.sha256(json.dumps(cfg, sort_keys=True).encode()).hexdigest()[:12]
    if MATERIAL_JS.exists() and f"stamp {stamp}" in MATERIAL_JS.read_text(encoding="utf-8")[:300]:
        return
    base = f"https://cdn.jsdelivr.net/npm/material-icon-theme@{version}/"
    man = json.loads(_fetch(base + "dist/material-icons.json"))
    defs = man["iconDefinitions"]

    def stem(icon: str) -> str:
        return Path(defs[icon]["iconPath"]).stem

    def table(src: dict) -> dict:
        return {k.lower(): stem(v) for k, v in src.items() if v in defs}

    ext = table(man.get("fileExtensions") or {})
    ext.update(table(cfg.get("language_ext") or {}))
    ext.update(table(cfg.get("override_ext") or {}))
    names = table(man.get("fileNames") or {})
    folders = table(man.get("folderNames") or {})
    light: dict[str, str] = {}
    lt = man.get("light") or {}
    for part, normal in (("fileExtensions", ext), ("fileNames", names), ("folderNames", folders)):
        for k, v in (lt.get(part) or {}).items():
            if v in defs and k.lower() in normal and normal[k.lower()] != stem(v):
                light[normal[k.lower()]] = stem(v)
    data = {"file": stem(man["file"]), "folder": stem(man["folder"]), "ext": ext, "names": names,
            "folders": folders, "light": light}
    used = {data["file"], data["folder"], *ext.values(), *names.values(), *folders.values(), *light.values()}
    folder = VENDOR / "material"
    _fetch_files([(base + f"icons/{s}.svg", folder / f"{s}.svg") for s in sorted(used)])
    if not (folder / "LICENSE.txt").exists():
        (folder / "LICENSE.txt").write_bytes(_fetch(base + "LICENSE"))
    for part in ("ext", "names", "folders"):     # icon -> "key|key|...": half the size of key -> icon
        grouped: dict[str, list[str]] = {}
        for k, v in data[part].items():
            grouped.setdefault(v, []).append(k)
        data[part] = {v: "|".join(sorted(ks)) for v, ks in sorted(grouped.items())}
    body = json.dumps(data, separators=(",", ":"), sort_keys=True)
    MATERIAL_JS.write_text(
        f"/* Generated by packaging/build_icons.py from material-icon-theme {version} (stamp {stamp}) - do not edit by hand.\n"
        "   Icon file in vendor/icons/material/ -> its extensions, file names or folder names (lower case, | between). */\n"
        f"const MATERIAL_ICONS = {body};\n", encoding="utf-8", newline="\n")
    print(f"material: {len(ext)} extensions, {len(names)} names, {len(folders)} folders, {len(used)} icons -> "
          f"{MATERIAL_JS.relative_to(ROOT)}")


def build_fluent(cfg: dict) -> None:
    base = f"https://cdn.jsdelivr.net/gh/microsoft/fluentui-emoji@{cfg['commit']}/"
    folder = VENDOR / "fluent-emoji"
    jobs = []
    for kind, src in cfg["icons"].items():
        d, _, f = src.partition("/")
        jobs.append((base + "assets/" + urllib.parse.quote(d) + f"/Flat/{f}_flat.svg", folder / f"{kind}.svg"))
    jobs.append((base + "LICENSE", folder / "LICENSE.txt"))
    _fetch_files(jobs)


def main() -> None:
    data = json.loads(MAP.read_text(encoding="utf-8"))
    if "_material" in data:
        build_material(data["_material"])
    if "_fluent" in data:
        build_fluent(data["_fluent"])
    icons = {k: v for k, v in data.items() if not k.startswith("_")}
    lines = [HEADER]
    for name, src in sorted(icons.items()):
        lines.append(_rule(f".ic-{name}", src))
    variants = data.get("_variants", {})
    for vname, v in variants.items():
        lines.append(f"/* variant: {vname} */\n")
        for name, src in v["icons"].items():
            if name not in icons:
                sys.exit(f"variant {vname}: {name!r} is not an icon in icons.json")
            lines.append(_rule(v["selector"].format(name=name), src))
    OUT.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(icons)} icons, {len(variants)} variants -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
